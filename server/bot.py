DEFAULT_LLM_MODEL = "gpt-5-mini"


def create_llm(choice: str | None = None):
    """Build an LLM service.

    Args:
        choice: A key from ``LLM_REGISTRY`` (sent by the client per session). Falls
            back to ``LLM_MODEL`` in .env, then the module default.

    Fails fast with a clear message on an unknown model name or a missing API key,
    so a bad selection surfaces at connect instead of mid-call.
    """
    choice = (choice or os.getenv("LLM_MODEL", DEFAULT_LLM_MODEL)).strip()
    if choice not in LLM_REGISTRY:
        raise ValueError(
            f"Unknown LLM model {choice!r}. Choose one of: {', '.join(LLM_REGISTRY)}"
        )

    service_cls, model_id, key_var, _label = LLM_REGISTRY[choice]
    api_key = os.getenv(key_var)
    if not api_key:
        raise ValueError(
            f"LLM model {choice!r} needs {key_var} set in your .env "
            f"(it resolves to provider model {model_id})."
        )

    logger.info(f"LLM: {choice} -> {model_id} ({service_cls.__name__})")
    return service_cls(
        api_key=api_key,
        settings=service_cls.Settings(
            model=model_id,
            system_instruction=SYSTEM_INSTRUCTION,
        ),
    )


# STT switcher — same registry pattern as the LLM/TTS ones. Each key maps to
# (factory, API-key env var, UI label). Deepgram is the strong English default;
# Sarvam Saaras (saaras:v3 in "codemix" mode) is purpose-built for Hinglish input,
# so a caller can code-switch Hindi/English and still be transcribed correctly.
DEFAULT_STT_MODEL = "deepgram"


def _build_deepgram_stt():
    """Deepgram (default). Strong English ASR; the general-purpose choice."""
    return DeepgramSTTService(api_key=os.getenv("DEEPGRAM_API_KEY"))


def _build_sarvam_stt():
    """Sarvam Saaras (best for Hinglish input). codemix mode keeps the code-switch."""
    api_key = os.getenv("SARVAM_API_KEY")
    if not api_key:
        raise ValueError(
            "STT model 'sarvam' needs SARVAM_API_KEY in your .env "
            "(free credits at dashboard.sarvam.ai — no card)."
        )
    return SarvamSTTService(
        api_key=api_key,
        settings=SarvamSTTService.Settings(model=os.getenv("SARVAM_STT_MODEL", "saaras:v3")),
        mode="codemix",
    )


STT_REGISTRY = {
    "deepgram": (_build_deepgram_stt, "DEEPGRAM_API_KEY", "Deepgram Nova (EN)"),
    "sarvam": (_build_sarvam_stt, "SARVAM_API_KEY", "Sarvam Saaras (Hinglish)"),
}


def create_stt(choice: str | None = None):
    """Build an STT service. See ``create_llm`` for the choice/fallback contract."""
    choice = (choice or os.getenv("STT_MODEL", DEFAULT_STT_MODEL)).strip()
