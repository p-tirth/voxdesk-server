# ---- Model discovery for the client dropdowns -------------------------------
# The client shows only models whose API key is actually configured, so a user
# can't pick something that will fail at connect. This endpoint is what it reads.


def available_models() -> dict:
    """List the models the client may offer, filtered to those with a key present.

    Returns a per-layer list of ``{"id", "label"}`` plus the current ``defaults``
    (from .env) so the UI can pre-select them.
    """
    llm = [
        {"id": key, "label": meta[3]}
        for key, meta in LLM_REGISTRY.items()
        if os.getenv(meta[2])
    ]
    stt = [
        {"id": key, "label": meta[2]}
        for key, meta in STT_REGISTRY.items()
        if os.getenv(meta[1])
    ]
    tts = [
        {"id": key, "label": meta[2]}
        for key, meta in TTS_REGISTRY.items()
        if os.getenv(meta[1])
    ]
    return {
        "llm": llm,
        "stt": stt,
        "tts": tts,
        "defaults": {
            "llm": os.getenv("LLM_MODEL", DEFAULT_LLM_MODEL).strip(),
            "stt": os.getenv("STT_MODEL", DEFAULT_STT_MODEL).strip(),
            "tts": os.getenv("TTS_MODEL", DEFAULT_TTS_MODEL).strip(),
        },
    }


@app.get("/models")
async def list_models() -> dict:
    """Configured models per layer, for the client's selection dropdowns.

    Registered on the runner's FastAPI app at import time (bot.py runs as
    ``__main__`` before ``main()`` starts the server), so it's live before connect.
    """
    return available_models()


async def run_bot(transport: BaseTransport, runner_args: RunnerArguments) -> None:
    """Run the voice bot for this session.

    Args:
        transport: The transport for this session, built by ``create_transport``
            (or by hand for the dial-out/SIP production flows).
        runner_args: Runner session arguments. Carries the request ``body``
            (e.g. dial-out settings, SIP call details) and ``session_id``; the
            standard web/telephony pipelines don't need it.
    """
    # Per-session model selection sent by the client in the connect body (see the
    # client's config.ts). Missing keys fall back to the .env defaults, so a plain
    # `uv run bot.py` (or an eval, which has no body) still works unchanged.
    selection = runner_args.body if isinstance(runner_args.body, dict) else {}

    logger.info(
        f"Starting bot | business={PROFILE.key} ({PROFILE.display_name}) | "
        f"tools={[t.__name__ for t in TOOLS]} | "
        f"selection={{'stt': {selection.get('stt')!r}, 'llm': {selection.get('llm')!r}, "
        f"'tts': {selection.get('tts')!r}}}"
    )

    # Each service is chosen by the client (or .env default). Built here, per
    # session, so two callers can run different stacks against the same server.
    stt = create_stt(selection.get("stt"))
    tts = create_tts(selection.get("tts"))
    llm = create_llm(selection.get("llm"))

    # Listing the tools on the context registers them with the LLM (direct
    # functions carry their own schema + handler — see tools.py). Empty for a
    # profile with no tools, which the context treats as "no tools".
    context = LLMContext(tools=TOOLS)
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(vad_analyzer=SileroVADAnalyzer()),
    )

    # Pipeline - assembled from reusable components
    pipeline = Pipeline(
        [
            transport.input(),
            stt,
            user_aggregator,
            llm,
            tts,
            transport.output(),
            assistant_aggregator,
        ]
    )

    # Surfaces the per-stage TTFB metrics as a readable per-turn ladder (and
    # writes JSONL for the scorecard). See latency.py.
    #
    # The mode is derived from the transport rather than an env var or a flag, so
    # it can't be forgotten: `-t eval` is the only way `create_transport` returns
    # an EvalTransport (runner.utils builds it from EvalRunnerArguments), and
    # every other transport — smallwebrtc for a browser call, Daily, telephony —
    # is a real session. An eval turn's timings are inflated by the harness's own
    # STT/TTS/judge sharing the machine, so the scorecard keeps them apart.
    mode = "eval" if isinstance(transport, EvalTransport) else "live"
    latency_observer = create_latency_observer(jsonl_path=LATENCY_JSONL_PATH, mode=mode)
    # Interruption handling is already wired (Silero VAD + InterruptionFrame);
    # this measures it — one row per time the caller talks over the bot. Same
    # `mode` provenance, for the same reason. See bargein.py.
    bargein_observer = create_bargein_observer(jsonl_path=BARGEIN_JSONL_PATH, mode=mode)

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        observers=[latency_observer, bargein_observer],
        # Shared, by reference, into every tool handler as params.app_resources.
        app_resources=DATA,
    )

    @worker.rtvi.event_handler("on_client_ready")
    async def on_client_ready(rtvi):
        # Kick off the conversation with a business-appropriate greeting.
        context.add_message({"role": "developer", "content": PROFILE.greeting})
        await worker.queue_frames([LLMRunFrame()])

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        await worker.cancel()

    runner = WorkerRunner(handle_sigint=False)

    await runner.add_workers(worker)
    await runner.run()


async def bot(runner_args: RunnerArguments):
    """Main bot entry point."""

    transport_params = {
        "webrtc": lambda: TransportParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
        # Behavioral evals: run with `-t eval` to drive this bot via `pipecat eval`.
        "eval": lambda: EvalTransportParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
    }

    transport = await create_transport(runner_args, transport_params)

    await run_bot(transport, runner_args)


if __name__ == "__main__":
    from pipecat.runner.run import main

    main()
